"""Build docs/app/data.js (crises + profiles for the web page) and tests/web_vectors.json
(Python reference results the JS port must match). Run with --check to detect drift."""
import json, os, sys
from dataclasses import asdict
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
from src.loader import load_crises, load_profiles
from src.exercise import run_exercise

DATA = os.path.join(ROOT, "docs", "app", "data.js")
VEC = os.path.join(ROOT, "tests", "web_vectors.json")


def build():
    raw = json.load(open(os.path.join(ROOT, "sample-data", "crises.json"), encoding="utf-8"))
    profiles = load_profiles()
    data = "/* generated by scripts/build_web.py from sample-data/ and config/ */\nvar WR_DATA = " + json.dumps({"crises": raw, "profiles": profiles}, ensure_ascii=False, indent=1) + ";\n"
    out = []
    for cid, c in load_crises().items():
        stages = []
        for s in run_exercise(c, profiles):
            d = asdict(s["decision"])
            stages.append({k: d[k] for k in ("recommended_option", "consensus_score", "dissent_score", "confidence", "votes", "option_scores")} | {"red_team_count": len(d["red_team_challenges"]), "review_required": d["executive_brief"]["executive_review_required"]})
        out.append({"crisis_id": cid, "stages": stages})
    return data, json.dumps(out, indent=1, sort_keys=True) + "\n"


def main():
    data, vec = build()
    if "--check" in sys.argv:
        bad = [p for p, t in ((DATA, data), (VEC, vec)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        if bad:
            print("stale:", bad); sys.exit(1)
        print("web data up to date"); return
    open(DATA, "w", encoding="utf-8").write(data); open(VEC, "w", encoding="utf-8").write(vec)
    print("wrote", DATA, VEC)


if __name__ == "__main__":
    main()
